import { readFile, writeFile } from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const read=async name=>JSON.parse(await readFile(new URL('data/'+name,root),'utf8'));
const originals=await read('originals.json'),authored=await read('generated.json'),authorSets=await read('author-sets.json');
if(originals.length!==80||authored.length!==400||authorSets.length!==20)throw Error('Unexpected corpus size');
const all=[...originals,...authored],ids=new Set();
all.forEach(task=>{
  if(ids.has(task.id)||task.number<1||task.number>20||task.options.length!==5||task.correct<0||task.correct>4)throw Error('Invalid task '+task.id);
  ids.add(task.id);
});
const sets=[...[2023,2024,2025,2026].map(year=>({
  id:'original-'+year,kind:'original',year,title:'Кенгуру '+year,grade:'3–4',
  taskIds:originals.filter(t=>t.source.year===year).sort((a,b)=>a.number-b.number).map(t=>t.id)
})),...authorSets];
const bank={
  id:'kangaroo-3-4',version:2,title:'3–4 классы',demo:false,
  sets,pools:Array.from({length:20},(_,i)=>({
    number:i+1,tasks:all.filter(t=>t.number===i+1).map(({verification,...task})=>task)
  }))
};
if(bank.pools.some(p=>p.tasks.length!==24))throw Error('Unbalanced number pools');
const script='// Generated by scripts/build-bank.mjs. Edit data sources, then rebuild.\n'+
  'globalThis.KANGAROO_BANK = '+JSON.stringify(bank)+';\n';
await writeFile(new URL('task-bank.js',root),script,'utf8');
await writeFile(new URL('data/catalog.json',root),JSON.stringify({
  grade:'3–4',originals:80,authored:400,total:480,questionsPerVariant:20,sets,
  pools:bank.pools.map(p=>({number:p.number,originals:4,authored:20,total:p.tasks.length}))
},null,2)+'\n','utf8');
console.log('Built '+all.length+' tasks, '+sets.length+' source sets, 20 pools × 24 tasks.');
